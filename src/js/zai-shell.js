  // 7. CAPTURE STOP BUTTON - detectar cuando el modelo esta respondiendo
  // ====================================================================
  function isModelResponding() {
    const stopBtn = document.querySelector(
      'div[role="button"][aria-label*="Stop" i], ' +
      'button[aria-label*="Stop" i], ' +
      'div[aria-label*="Stop" i] button'
    );
    return !!stopBtn;
  }

  let lastResponding = false;
  function watchResponseState() {
    setInterval(() => {
      if (document.hidden) return;
      const now = isModelResponding();
      // GA3: tell native about streaming state so it can toggle wake lock
      if (now !== lastResponding) {
        try {
          if (window.Capacitor?.Plugins?.ZaiShell) {
            window.Capacitor.Plugins.ZaiShell.setStreamingState({ active: now });
          }
        } catch (e) {}
      }
      if (lastResponding && !now) {
        log('Response completed');
        try {
          if (window.Capacitor?.Plugins?.Haptics) {
            window.Capacitor.Plugins.Haptics.impact({ style: 'LIGHT' });
          }
          if (document.hidden) {
            sendBackgroundNotification();
          }
          autoSaveConversation();
        } catch (e) {}
      }
      lastResponding = now;
    }, 1000);
  }

  /**
   * Envía una notificación local nativa cuando el modelo termina de responder
   * y la app está en background.
   */
  async function sendBackgroundNotification() {
    try {
      if (!window.Capacitor?.Plugins?.LocalNotifications) return;
      const { LocalNotifications } = window.Capacitor.Plugins;
      // Solicitar permiso si no lo tenemos
      const perm = await LocalNotifications.checkPermissions();
      if (perm.display !== 'granted') {
        const req = await LocalNotifications.requestPermissions();
        if (req.display !== 'granted') return;
      }
      // Obtener preview de la ultima respuesta
      const msgs = findMessages();
      const userMsgs = findUserMessages();
      const userSet = new Set(userMsgs);
      let lastResponse = null;
      for (let i = msgs.length - 1; i >= 0; i--) {
        if (!userSet.has(msgs[i])) { lastResponse = msgs[i]; break; }
      }
      let preview = 'Toca para abrir';
      if (lastResponse) {
        const text = (lastResponse.innerText || '').trim();
        if (text) preview = text.slice(0, 80) + (text.length > 80 ? '...' : '');
      }
      // MEDIUM #25: monotonic counter to avoid collision when 2 responses complete in same second
      sendBackgroundNotification._counter = (sendBackgroundNotification._counter || 0) + 1;
      const notifId = (sendBackgroundNotification._counter % 100000) + 1;
      await LocalNotifications.schedule({
        notifications: [{
          id: notifId,
          title: '⚡ Z.ai respondió',
          body: preview,
          largeBody: preview,
          smallIcon: 'ic_notification',
          iconColor: '#3b82f6',
          sound: 'bell.wav',
          // HIGH #40: schedule at least 1s ahead (Android rounds to next minute for exact alarms)
          schedule: { at: new Date(Date.now() + 1000) },
          actionTypeId: 'OPEN_APP',
          extra: { type: 'response_complete' }
        }]
      });
      log('Background notification sent (id=' + notifId + ')');
    } catch (e) {
      log('Notification failed', e);
    }
  }


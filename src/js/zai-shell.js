  // ====================================================================
  // 3. DOM CLEANUP - elimina mensajes antiguos para liberar RAM
  // ====================================================================
  function findMessages() {
    // z.ai usa clases Tailwind hasheadas; buscar multiples patrones
    const selectors = [
      '[class*="markdown-render"]',
      '[class*="message-content"]',
      '[class*="chat-message"]',
      '.prose',
      'article',
    ];
    const seen = new Set();
    const msgs = [];
    for (const sel of selectors) {
      try {
        document.querySelectorAll(sel).forEach(el => {
          if (seen.has(el)) return;
          seen.add(el);
          // Solo contar si tiene contenido sustancial
          if ((el.textContent || '').trim().length > 10) {
            msgs.push(el);
          }
        });
      } catch (e) {}
    }
    return msgs;
  }

  function findUserMessages() {
    // Mensajes de usuario contienen el boton Edit con clase especifica
    const out = [];
    document.querySelectorAll('.edit-user-message-button, [class*="user-message"]').forEach(el => {
      const container = el.closest('[class*="message"], article, .prose');
      if (container && !out.includes(container)) out.push(container);
    });
    return out;
  }

  let cleanupCount = 0;
  function cleanupOldMessages() {
    const msgs = findMessages();
    if (msgs.length <= CONFIG.MAX_MESSAGES) return;

    // Marcar los antiguos como hidden en vez de eliminarlos (preserva scroll)
    const toHide = msgs.length - CONFIG.MAX_MESSAGES;
    let hidden = 0;
    for (let i = 0; i < toHide && i < msgs.length; i++) {
      const el = msgs[i];
      if (el.style.display === 'none') continue;
      // Crear placeholder para preservar altura de scroll
      const placeholder = document.createElement('div');
      placeholder.style.height = el.offsetHeight + 'px';
      placeholder.style.width = '100%';
      placeholder.className = 'zai-shell-placeholder';
      placeholder.dataset.originalContent = 'true';
      el.parentNode.insertBefore(placeholder, el);
      el.style.display = 'none';
      el.dataset.zaiShellHidden = 'true';
      hidden++;
    }
    cleanupCount += hidden;
    log('Hidden ' + hidden + ' old messages (total cleaned: ' + cleanupCount + ')');
  }

  function startCleanup() {
    setInterval(() => {
      // GA2: skip when hidden
      if (document.hidden) return;
      cleanupOldMessages();
    }, CONFIG.CLEANUP_INTERVAL_MS);
    // Tambien cuando el usuario scrollea arriba (libera mas)
    let scrollTimer = null;
    window.addEventListener('scroll', () => {
      if (scrollTimer) clearTimeout(scrollTimer);
      scrollTimer = setTimeout(cleanupOldMessages, 1000);
    }, { passive: true });
    log('DOM cleanup started (max ' + CONFIG.MAX_MESSAGES + ' messages)');
  }


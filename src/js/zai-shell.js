  // 18. OUTGOING PERSISTENCE - guarda el texto que escribes mientras
  // se envia o si la app se cierra, para que no se pierda
  // ====================================================================
  let pendingOutgoing = null;

  function setupOutgoingPersistence() {
    // CRITICAL #2: replaced body-wide MutationObserver with input listener on textarea
    // HIGH #7: replaced 1s setInterval with input event (debounced)

    function findTa() {
      return document.querySelector('textarea#chat-input, textarea[placeholder*="Message" i], textarea[placeholder*="Send" i], textarea');
    }

    // Debounced save
    let saveTimer = null;
    function saveDraft(text) {
      if (saveTimer) clearTimeout(saveTimer);
      saveTimer = setTimeout(() => {
        try {
          if (text && text.trim()) {
            localStorage.setItem('zai-shell-draft', text);
          } else {
            localStorage.removeItem('zai-shell-draft');
          }
        } catch (e) {}
      }, 500);
    }

    // 1. Hook input event on textarea (reattach if z.ai recreates it)
    let lastTa = null;
    function attachInputListener() {
      const ta = findTa();
      if (ta === lastTa) return;
      if (lastTa) {
        try { lastTa.removeEventListener('input', onInput); } catch (e) {}
      }
      lastTa = ta;
      if (ta) {
        ta.addEventListener('input', onInput, { passive: true });
        // Also detect when textarea empties (message sent)
        ta.addEventListener('input', onSendDetect, { passive: true });
      }
    }

    function onInput(e) {
      saveDraft(e.target.value || '');
    }

    function onSendDetect(e) {
      // Si el textarea se vacia pero habia draft, se envio
      if (!e.target.value && localStorage.getItem('zai-shell-draft')) {
        const sent = localStorage.getItem('zai-shell-draft');
        localStorage.removeItem('zai-shell-draft');
        pendingOutgoing = {
          text: sent,
          timestamp: Date.now(),
          confirmed: false
        };
        log('Outgoing message tracked: ' + sent.length + ' chars');
        setTimeout(() => confirmOutgoingMessage(), 5000);
      }
    }

    // Poll to reattach listener (textarea may be recreated by z.ai SPA)
    setInterval(() => {
      if (document.hidden) return;
      attachInputListener();
    }, 3000);

    // 2. Al cargar, restaurar draft
    setTimeout(() => {
      try {
        const draft = localStorage.getItem('zai-shell-draft');
        if (draft) {
          const ta = findTa();
          if (ta && !ta.value) {
            // MEDIUM #16: null check on descriptor
            const desc = Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value');
            if (desc && desc.set) {
              desc.set.call(ta, draft);
            } else {
              ta.value = draft;
            }
            ta.dispatchEvent(new Event('input', { bubbles: true }));
            log('Draft restored: ' + draft.length + ' chars');
          }
        }
      } catch (e) {}
    }, 2000);

    // Initial attach
    attachInputListener();

    log('Outgoing persistence installed (input listener)');
  }

  function confirmOutgoingMessage() {
    if (!pendingOutgoing || pendingOutgoing.confirmed) return;
    // Buscar si el mensaje ya aparece en el DOM
    const userMsgs = findUserMessages();
    for (const el of userMsgs) {
      const text = (el.innerText || '').trim();
      if (text && pendingOutgoing.text && text.includes(pendingOutgoing.text.slice(0, 30))) {
        pendingOutgoing.confirmed = true;
        log('Outgoing confirmed in DOM');
        return;
      }
    }
    // Si despues de 10s no aparece, marcar como "pendiente" en historial
    if (Date.now() - pendingOutgoing.timestamp > 10000) {
      log('Outgoing message not confirmed, marking as pending');
      // Guardar en historial como conversacion fallida?
      // Por ahora solo log
      pendingOutgoing = null;
    } else {
      setTimeout(() => confirmOutgoingMessage(), 3000);
    }
  }

  // ====================================================================
  // 15. NATIVE SSE BRIDGE - intercepta streams del WebView y los enruta
  // a una conexion SSE nativa en Kotlin que sobrevive al background
  // ====================================================================

  /**
   * Patcheamos window.fetch para detectar requests SSE/streaming.
   * Cuando detectamos una request que parece SSE (Accept: text/event-stream
   * o URL con /stream o /chat/completion), la desviamos al plugin nativo
   * ZaiSseBridge que mantiene la conexion en Kotlin.
   *
   * Devolvemos al WebView un ReadableStream falso que recibe los eventos
   * del nativo, asi z.ai no se entera del cambio.
   */
  function installSseInterceptor() {
    if (!window.Capacitor?.Plugins?.ZaiSseBridge) {
      log('ZaiSseBridge not available, skipping SSE interceptor');
      return;
    }
    if (window.__ZAI_SSE_INTERCEPTED__) return;
    window.__ZAI_SSE_INTERCEPTED__ = true;

    const SseBridge = window.Capacitor.Plugins.ZaiSseBridge;
    const originalFetch = window.fetch;
    let streamCounter = 0;

    // CRITICAL #24: store listener handle for proper cleanup
    const streamCallbacks = new Map();
    let sseListenerHandle = null;
    SseBridge.addListener('sse:event').then(handle => {
      sseListenerHandle = handle;
      handle.addListener((event) => {
        const cb = streamCallbacks.get(event.id);
        if (!cb) return;
        if (event.type === 'open') {
          cb.onOpen && cb.onOpen(event.code || 200);
        } else if (event.type === 'event') {
          cb.onEvent && cb.onEvent(event.eventType || 'message', event.data || '', event.eventId);
        } else if (event.type === 'closed') {
          cb.onClose && cb.onClose();
          streamCallbacks.delete(event.id);
        } else if (event.type === 'error') {
          cb.onError && cb.onError(new Error(event.message || 'SSE error'), event.code);
          streamCallbacks.delete(event.id);
        }
      });
    }).catch(e => log('SseBridge.addListener failed', e));

    function isStreamRequest(url, options) {
      const lowerUrl = (url || '').toLowerCase();
      const accept = (options?.headers?.Accept || options?.headers?.accept || '').toLowerCase();
      if (accept.includes('text/event-stream')) return true;
      if (lowerUrl.includes('/stream')) return true;
      if (lowerUrl.includes('/chat/completion')) return true;
      if (lowerUrl.includes('/api/chat') && !lowerUrl.includes('/api/chats/')) return true;
      if (lowerUrl.includes('/completion')) return true;
      return false;
    }

    window.fetch = async function(input, init) {
      // CRITICAL #26: handle Request objects - extract method/headers/body/credentials
      let url, options;
      if (input instanceof Request) {
        url = input.url;
        options = {
          method: input.method,
          headers: input.headers,
          body: init?.body || input.body,
          credentials: input.credentials,
          mode: input.mode,
          ...init
        };
      } else {
        url = typeof input === 'string' ? input : (input?.url || '');
        options = init || {};
      }

      if (!isStreamRequest(url, options)) {
        return originalFetch(input, init);
      }

      log('Intercepting SSE stream:', url.slice(0, 100));

      const headersObj = {};
      if (options.headers) {
        if (options.headers instanceof Headers) {
          options.headers.forEach((v, k) => { headersObj[k] = v; });
        } else if (Array.isArray(options.headers)) {
          options.headers.forEach(([k, v]) => { headersObj[k] = v; });
        } else {
          // MEDIUM #26: filter prototype pollution keys
          Object.entries(options.headers).forEach(([k, v]) => {
            if (!['__proto__', 'constructor', 'prototype'].includes(k)) {
              headersObj[k] = v;
            }
          });
        }
      }
      if (options.method?.toUpperCase() === 'POST' && !headersObj['Content-Type'] && !headersObj['content-type']) {
        headersObj['Content-Type'] = 'application/json';
      }

      // CRITICAL #26: serialize body for native transport
      let bodyStr = null;
      if (typeof options.body === 'string') {
        bodyStr = options.body;
      } else if (options.body instanceof URLSearchParams) {
        bodyStr = options.body.toString();
        headersObj['Content-Type'] = headersObj['Content-Type'] || 'application/x-www-form-urlencoded';
      } else if (options.body instanceof FormData) {
        // FormData no se puede serializar facilmente - fallback al fetch original
        log('FormData body detected, falling back to original fetch');
        return originalFetch(input, init);
      } else if (options.body instanceof Blob) {
        // Convertir Blob a texto via FileReader - pero es async, mejor fallback
        log('Blob body detected, falling back to original fetch');
        return originalFetch(input, init);
      } else if (options.body) {
        try { bodyStr = String(options.body); } catch (e) {
          log('Could not serialize body, falling back');
          return originalFetch(input, init);
        }
      }

      const streamId = 'sse-' + (++streamCounter) + '-' + Date.now();

      let controllerRef = null;
      const readable = new ReadableStream({
        start(controller) { controllerRef = controller; },
        cancel() {
          SseBridge.stopStream({ id: streamId });
          streamCallbacks.delete(streamId);
        }
      });

      const encoder = new TextEncoder();

      streamCallbacks.set(streamId, {
        onOpen: (code) => { log('SSE stream opened:', streamId, 'code', code); },
        onEvent: (eventType, data, eventId) => {
          if (!controllerRef) return;
          let chunk = '';
          if (eventId) chunk += 'id: ' + eventId + '\n';
          if (eventType && eventType !== 'message') chunk += 'event: ' + eventType + '\n';
          const dataLines = data.split('\n');
          for (const line of dataLines) chunk += 'data: ' + line + '\n';
          chunk += '\n';
          try { controllerRef.enqueue(encoder.encode(chunk)); } catch (e) {}
        },
        onClose: () => {
          if (controllerRef) { try { controllerRef.close(); } catch (e) {} }
        },
        onError: (err, code) => {
          log('SSE stream error:', streamId, err.message);
          if (controllerRef) { try { controllerRef.error(err); } catch (e) {} }
        }
      });

      try {
        await SseBridge.startStream({
          id: streamId,
          url: url,
          method: options.method || 'GET',
          headers: headersObj,
          body: bodyStr
        });
      } catch (e) {
        log('Failed to start native SSE, fallback:', e.message);
        return originalFetch(input, init);
      }

      return new Response(readable, {
        status: 200,
        statusText: 'OK',
        headers: {
          'Content-Type': 'text/event-stream',
          'Cache-Control': 'no-cache',
          'Connection': 'keep-alive'
        }
      });
    };

    log('SSE interceptor installed (fetch patched)');
  }

